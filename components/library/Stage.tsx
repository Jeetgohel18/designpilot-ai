"use client";
import { forwardRef, useEffect, useImperativeHandle, useMemo, useRef } from "react";
import { attachBehaviors } from "@/lib/library/behavior";
import { allCss, SHADOWS, WIDTHS, stageBackground, stageVars, type Custom } from "@/lib/library";
import { scopeCss } from "@/lib/library/scope";
import type { Ctx } from "@/lib/library/types";

const SCOPED = scopeCss(allCss(), ".dp-stage");
/** One <style> element with all component CSS scoped under .dp-stage. Render once per library view. */
export function LibraryStyles() { return <style data-dp-library>{SCOPED + "\n.dp-stage .ds-i{pointer-events:none}"}</style>; }

export interface StageProps { html: string; ctx: Ctx; custom: Custom; interactive?: boolean; className?: string; minHeight?: number; padded?: boolean; ariaLabel?: string; forceWidth?: boolean }

/** Renders component markup (generated by our own library, never user input) with the project's tokens as CSS variables. */
export const Stage = forwardRef<HTMLDivElement, StageProps>(function Stage({ html, ctx, custom, interactive = true, className = "", minHeight, padded = true, ariaLabel, forceWidth = true }, ref) {
  const el = useRef<HTMLDivElement>(null);
  useImperativeHandle(ref, () => el.current as HTMLDivElement);
  const vars = useMemo(() => stageVars(ctx, custom), [ctx, custom]);
  const bg = stageBackground(ctx, custom.bg);
  useEffect(() => { if (!interactive || !el.current) return; return attachBehaviors(el.current); }, [interactive]);
  const w = forceWidth ? WIDTHS[custom.width] : 0;
  return (
    <div ref={el} role="group" aria-label={ariaLabel ?? "Component preview"} className={`dp-stage ${className}`}
      style={{ ...(vars as React.CSSProperties), background: bg ?? "transparent", color: ctx.colors.text, width: w ? Math.min(w, 9999) : undefined, maxWidth: "100%", minHeight, margin: w ? "0 auto" : undefined, padding: padded ? 24 : 0, position: "relative", overflow: "hidden", fontFamily: "var(--font-body)" }}>
      <div className="ds" dangerouslySetInnerHTML={{ __html: html }} />
    </div>
  );
});
export { SHADOWS };
