import { cssSnippet, fontFamilyCss, linkTag } from "../fonts";
import { darkTheme, exportCss, exportDtcg } from "./palette";
import { ROLES, type Direction, type Project } from "../types";
import { contrast } from "../color";
import { describe } from "../brand/concepts";
import { ARCH } from "../brand/render";

export const directionOf = (p: Project): Direction | undefined => p.directions.find((d) => d.id === p.selectedDirection) ?? p.directions[0];

export function tokensJson(d: Direction): string {
  return JSON.stringify({
    $description: `Design tokens — ${d.name}`,
    ...JSON.parse(exportDtcg(d.palette.colors)),
    font: { heading: { $type: "fontFamily", $value: fontFamilyCss(d.fonts.heading) }, body: { $type: "fontFamily", $value: fontFamilyCss(d.fonts.body) } },
    radius: { sm: { $type: "dimension", $value: "6px" }, md: { $type: "dimension", $value: "12px" }, lg: { $type: "dimension", $value: "20px" } },
    space: Object.fromEntries([4, 8, 12, 16, 24, 32, 48, 64].map((n) => [String(n), { $type: "dimension", $value: `${n}px` }])),
  }, null, 2);
}

export function fullCss(d: Direction): string {
  return `${cssSnippet(d.fonts)}\n\n${exportCss(d.palette.colors, d.name)}\n\n:root {\n  --radius-sm: 6px;\n  --radius-md: 12px;\n  --radius-lg: 20px;\n  --space-1: 4px; --space-2: 8px; --space-3: 12px; --space-4: 16px; --space-6: 24px; --space-8: 32px;\n}`;
}

export function tailwindV4Theme(d: Direction): string {
  const c = d.palette.colors;
  return `/* app/globals.css (Tailwind v4) */\n@import "tailwindcss";\n\n@theme {\n${ROLES.map((r) => `  --color-${r}: ${c[r]};`).join("\n")}\n  --font-heading: ${fontFamilyCss(d.fonts.heading)};\n  --font-body: ${fontFamilyCss(d.fonts.body)};\n}`;
}

export function nextFontSnippet(d: Direction): string {
  const id = (n: string) => n.replace(/ /g, "_");
  return `// app/layout.tsx\nimport { ${id(d.fonts.heading)}, ${id(d.fonts.body)} } from "next/font/google";\n\nconst heading = ${id(d.fonts.heading)}({ subsets: ["latin"], variable: "--font-heading" });\nconst body = ${id(d.fonts.body)}({ subsets: ["latin"], variable: "--font-body" });\n// <html className={\`\${heading.variable} \${body.variable}\`}>`;
}

export function accessibilityNotes(d: Direction): string[] {
  const c = d.palette.colors, dk = darkTheme(c);
  const r = (a: string, b: string) => contrast(a, b).toFixed(2);
  return [
    `Body text on background: ${r(c.text, c.background)}:1 (light), ${r(dk.text, dk.background)}:1 (dark). WCAG AA needs 4.5:1.`,
    `Primary on background: ${r(c.primary, c.background)}:1 — safe for links and large UI. Accent on background: ${r(c.accent, c.background)}:1${contrast(c.accent, c.background) < 4.5 ? " — below 4.5:1, so use accent for fills/graphics, not body-size text" : ""}.`,
    "Always keep a visible focus ring (2px, using the primary color, 2px offset).",
    "Don't rely on color alone to convey state; pair with an icon or text.",
  ];
}

/** Brand identity section for the brief. Empty until the user has chosen a logo concept. */
export function brandSection(p: Project): string {
  const b = p.brand, c = b?.concepts.find((x) => x.id === b.selected);
  if (!b || !c) return "";
  const a = describe(c, b.profile);
  return `
## Brand identity (chosen logo concept)
**Brand:** ${b.profile.name} · **Concept:** ${ARCH[c.archetype].label} (a generated design concept; not checked against existing logos or trademarks)
**Logo colours:** ink ${c.palette.ink}, accent ${c.palette.accent}, background ${c.palette.bg}, deep ${c.palette.deep}
**Logo lettering:** ${c.font.family} ${c.font.weight}${c.caps ? ", capitals" : ""}
**Idea:** ${a.idea}
**Best use:** ${a.bestUse}
**Weaknesses to know about:** ${a.weakness}
${b.profile.tone ? `**Tone of voice:** ${b.profile.tone}\n` : ""}Logo files (SVG, PNG, PDF) and the brand kit come from the Logo & brand tab. Use the exported files; do not redraw the logo.
`;
}

export function designBrief(p: Project): string {
  const d = directionOf(p);
  const pr = p.profile;
  const L = (a: string[]) => a.map((x) => `- ${x}`).join("\n");
  return `# Design brief — ${p.name}

> Generated by DesignPilot (${p.source === "ai" ? "AI analysis" : "local rule-based analysis"}). Suggestions, not verified research.

## Project
${p.brief}

**Type:** ${pr.projectType} · **Industry:** ${pr.industry} (${pr.niche})
**Audience:** ${pr.audience}
**Platforms:** ${pr.platforms.join("; ")}

## Goals
${L(pr.businessGoals)}

## User needs
${L(pr.userNeeds)}

## Brand personality & mood
${pr.brandPersonality.join(", ")} — ${pr.visualMood.join(", ")}

## Known design challenges
${L(pr.challenges)}
${brandSection(p)}${d ? `
## Selected direction: ${d.name}
${d.summary}

**Typography:** ${d.fonts.heading} (headings) + ${d.fonts.body} (body). ${d.fontRationale}
**Color:** ${ROLES.map((r) => `${r} ${d.palette.colors[r]}`).join(" · ")}
**Imagery:** ${d.imageStyle}
**Illustration:** ${d.illustrationStyle}
**Icons:** ${d.iconStyle}
**Logo direction:** ${d.logoDirection}

### Principles
${L(d.principles)}

### Interface components to design first
${L(d.components)}

### Accessibility
${L(accessibilityNotes(d))}
` : ""}
## Search keywords
${pr.keywords.join(", ")}
`;
}

export function handoffBundle(d: Direction) {
  return { css: fullCss(d), tokens: tokensJson(d), tailwind: tailwindV4Theme(d), fontLink: linkTag([d.fonts.heading, d.fonts.body]), nextFont: nextFontSnippet(d) };
}

export function logoConcepts(name: string, d: Direction) {
  const brand = name.trim() || "[Brand]";
  const initials = brand.replace(/[^A-Za-z ]/g, "").split(/\s+/).filter(Boolean).map((w) => w[0]).join("").slice(0, 2).toUpperCase() || "B";
  const base = `${d.name.toLowerCase()} aesthetic, ${d.palette.colors.primary} and ${d.palette.colors.background} palette, vector logo, flat, on a plain background, no text artifacts`;
  return [
    { type: "Wordmark", idea: `"${brand}" set in ${d.fonts.heading}-style lettering. ${d.logoDirection}.`, prompt: `Original wordmark logo for a brand named "${brand}", custom letterforms inspired by ${d.fonts.heading}, ${base}` },
    { type: "Monogram", idea: `"${initials}" in a simple geometric container (circle, arch or square) — a seal for packaging, favicon and social avatars.`, prompt: `Original monogram logo of the letters "${initials}", minimal, geometric container, ${base}` },
    { type: "Symbol", idea: `A simple mark that reflects the project's story (${d.imageStyle.split(",")[0].toLowerCase()}). Must read at 16px.`, prompt: `Original abstract symbol logo representing ${d.name.toLowerCase()} values, simple shapes, scalable, ${base}` },
    { type: "Combination mark", idea: `Symbol + "${brand}" wordmark with a horizontal and a stacked lockup.`, prompt: `Original combination mark logo, simple symbol beside the wordmark "${brand}", horizontal lockup, ${base}` },
  ];
}
