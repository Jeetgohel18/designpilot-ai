export interface ExportEnv { project: { name: string }; component: Component; cfg: Cfg; ctx: Ctx; custom: Custom }

/** `skincare-buttons-primary-lg@2x.png` style names. */
export function fileName(env: ExportEnv, ext: string, scale?: number): string {
  const { component: c, cfg } = env; const parts = [slug(env.ctx.brand), c.id];
  if (c.controls.some((x) => x.key === "variant") && cfg.variant) parts.push(slug(cfg.variant));
  if (c.controls.some((x) => x.key === "size") && cfg.size !== "md") parts.push(cfg.size);
  return `${parts.join("-")}${scale && scale > 1 ? `@${scale}x` : ""}.${ext}`;
}

const FONT_NEEDS = (ctx: Ctx) => [{ family: ctx.heading, weight: 700 }, { family: ctx.heading, weight: 400 }, { family: ctx.body, weight: 400 }, { family: ctx.body, weight: 600 }, { family: ctx.body, weight: 700 }];
export const fontFamiliesOf = (ctx: Ctx) => [ctx.heading, ctx.body];

export async function makeResolver(ctx: Ctx): Promise<FontResolver> { return preloadFonts(FONT_NEEDS(ctx)); }
export function makeMeasure(ctx: Ctx, resolve: FontResolver): Measure {
  return (t, size, weight = 400, fam = "body") => textWidth(resolve(fam === "heading" ? ctx.heading : ctx.body, weight >= 600 ? 700 : weight >= 500 ? 600 : 400) ?? resolve(fam === "heading" ? ctx.heading : ctx.body, 400), t, size, 0, weight >= 600);
}

/** Vector scene for a component, with text converted to outlines when the fonts could be loaded. */
export async function buildVector(env: ExportEnv): Promise<{ vec: Vec; outlined: boolean; missing: string[] }> {
  const c = env.component;
  if (!c.vector) throw new Error(c.vectorNote ?? `${c.name} contains HTML layout that can't be represented faithfully as SVG. Use PNG, PDF or code export instead.`);
  const resolve = await makeResolver(env.ctx);
  const vec = c.vector(env.cfg, env.ctx, makeMeasure(env.ctx, resolve));
  const { vec: out, missing } = outlineScene(vec, resolve);
  return { vec: out, outlined: missing.length === 0, missing };
}

export async function exportSvg(env: ExportEnv) {
  const { vec, outlined, missing } = await buildVector(env);
  return { name: fileName(env, "svg"), svg: toSvg({ ...vec, bg: vec.bg }), outlined, missing, width: vec.w, height: vec.h };
}

export async function exportRasterFile(el: HTMLElement, env: ExportEnv, o: { format: RasterFormat; scale: number; background: string | null; quality: number }) {
  const r = await elementToBlob(el, { format: o.format, scale: o.scale, background: o.background, quality: o.quality, fontFamilies: fontFamiliesOf(env.ctx) });
  return { name: fileName(env, o.format === "png" ? "png" : "jpg", o.scale), ...r };
}

/** A specification sheet: rendered preview + real, selectable text for variants, states, tokens and guidance. */
export async function exportPdf(el: HTMLElement, env: ExportEnv, bg: string): Promise<{ name: string; bytes: Uint8Array; pages: number }> {
  const { component: c, ctx, custom, cfg } = env;
  const shot = await elementToBlob(el, { format: "jpeg", scale: 2, background: bg, quality: 0.92, fontFamilies: fontFamiliesOf(ctx) });
  const doc = new PdfDoc(`${c.name} — ${ctx.brand} component specification`);
  const sh = new Sheet(doc, `${ctx.brand} · ${c.name} · generated by DesignPilot AI`);
  sh.para(`${CATEGORY_LABEL[c.category].toUpperCase()}`, { size: 8.5, font: "F2", color: "#7a6cff" });
  sh.heading(c.name, 22);
  sh.para(c.desc, { size: 11, color: "#444444" });
  sh.h2("Preview");
  sh.image(doc.addJpeg(await blobBytes(shot.blob), shot.width, shot.height), sh.width, 330);
  const rows: [string, string][] = [["Direction", `${ctx.heading} (headings) + ${ctx.body} (body)`], ["Variant", cfg.variant || "default"], ["Size", cfg.size], ["Icon", cfg.iconPos], ["Radius / border", `${custom.radius}px / ${custom.border}px`], ["Weight / density", `${custom.weight} / ${custom.sp}×`], ["Theme", ctx.dark ? "Dark (derived)" : "Light"]];
  sh.table(rows, { keyW: 130 });
  const variants = c.controls.find((x) => x.key === "variant"); if (variants) { sh.h2("Variants"); sh.bullets(variants.options.map((o) => o.label)); }
  const states = c.states?.(ctx); if (states?.length) { sh.h2("States"); sh.bullets(states.map((s) => s.label)); }
  sh.h2("Design tokens"); sh.table(tokenRows(c, stageVars(ctx, custom)), { keyW: 150, mono: true, size: 9 });
  sh.h2("When to use"); sh.bullets(c.use);
  sh.h2("Avoid"); sh.bullets(c.avoid);
  sh.h2("Accessibility"); sh.bullets(c.a11y);
  sh.h2("Spacing & sizing"); sh.bullets(c.spacing);
  sh.h2("Implementation notes"); sh.bullets([...c.notes, "Responsive behavior uses CSS container queries; wrap the component in an element with container-type: inline-size (the .ds wrapper does this)."]);
  const bytes = doc.build();
  return { name: fileName(env, "pdf").replace(/\.pdf$/, "-spec.pdf"), bytes, pages: doc.pages.length };
}

