import { ApiError, GoogleGenAI } from "@google/genai";

// Google Gemini via the official Google Gen AI SDK. Server-only: GEMINI_API_KEY is never sent to the browser.
// Default model is a stable (non-preview) Flash model that has a free tier; override with GEMINI_MODEL.
// Free-tier limits are enforced by Google (the API returns 429 when exceeded). We never enable billing:
// that only happens if YOU enable it on your Google Cloud project.
export const DEFAULT_MODEL = "gemini-2.5-flash";
export const geminiModel = () => process.env.GEMINI_MODEL?.trim() || DEFAULT_MODEL;
export const aiConfigured = () => !!process.env.GEMINI_API_KEY?.trim();

export type AiErrorKind = "missing_key" | "invalid_key" | "quota" | "blocked" | "bad_output" | "timeout" | "provider";

export class AiError extends Error {
  constructor(public kind: AiErrorKind, public status?: number) { super(kind); }
}

/** Plain-language message shown in the UI. Never includes provider error text (which could echo request details). */
export function userMessage(kind: AiErrorKind, what: "analysis" | "assistant"): string {
  const tail = what === "analysis" ? "This analysis was generated by the built-in rule-based engine instead." : "This answer comes from the built-in offline assistant instead.";
  switch (kind) {
    case "missing_key": return `Gemini isn't configured on this server (GEMINI_API_KEY is missing). ${tail}`;
    case "invalid_key": return `The Gemini API key was rejected as invalid or not permitted. Check GEMINI_API_KEY in your hosting settings. ${tail}`;
    case "quota": return `The free Gemini quota is used up for now (rate or daily limit). Try again later. ${tail}`;
    case "blocked": return `Gemini declined to answer this request. ${tail}`;
    case "bad_output": return `Gemini returned an answer we couldn't use. ${tail}`;
    case "timeout": return `Gemini took too long to respond. ${tail}`;
    default: return `The Gemini service had a problem. ${tail}`;
  }
}

export function classifyError(err: unknown): AiError {
  if (err instanceof AiError) return err;
  const status = err instanceof ApiError ? err.status : typeof (err as { status?: unknown })?.status === "number" ? (err as { status: number }).status : undefined;
  const text = err instanceof Error ? err.message : "";
  if (err instanceof Error && (err.name === "AbortError" || err.name === "TimeoutError" || /timed? ?out|aborted/i.test(text))) return new AiError("timeout", status);
  if (status === 429 || /RESOURCE_EXHAUSTED|quota/i.test(text)) return new AiError("quota", 429);
  if (status === 401 || status === 403 || /API[_ ]KEY[_ ](INVALID|NOT VALID)|API key not valid|PERMISSION_DENIED/i.test(text)) return new AiError("invalid_key", status);
  if (status === 400 && /API key/i.test(text)) return new AiError("invalid_key", 400);
  return new AiError("provider", status);
}

/** Call Gemini once. `json: true` asks for a JSON-only response. Throws AiError (never a raw provider error). */
export async function generate(opts: { system: string; prompt: string; json?: boolean; maxTokens?: number; timeoutMs?: number }): Promise<string> {
  const key = process.env.GEMINI_API_KEY?.trim();
  if (!key) throw new AiError("missing_key");
  try {
    const ai = new GoogleGenAI({ apiKey: key, httpOptions: { timeout: opts.timeoutMs ?? 40_000 } });
    const res = await ai.models.generateContent({
      model: geminiModel(),
      contents: opts.prompt,
      config: {
        systemInstruction: opts.system,
        maxOutputTokens: opts.maxTokens ?? 6000,
        temperature: opts.json ? 0.7 : 0.6,
        ...(opts.json ? { responseMimeType: "application/json" } : {}),
        thinkingConfig: { thinkingBudget: 0 }, // short, fast answers: keeps free-tier token use low
      },
    });
    if (res.promptFeedback?.blockReason) throw new AiError("blocked");
    const text = res.text;
    if (!text?.trim()) throw new AiError("bad_output");
    return text;
  } catch (err) {
    throw classifyError(err);
  }
}

export function extractJson(text: string): unknown {
  const start = text.indexOf("{"), end = text.lastIndexOf("}");
  if (start < 0 || end < start) throw new AiError("bad_output");
  try { return JSON.parse(text.slice(start, end + 1)); } catch { throw new AiError("bad_output"); }
}

/** Log only the error category and HTTP status — never the key, the prompt, or provider message text. */
export const logAiError = (where: string, e: AiError) => console.error(`[${where}] Gemini call failed: ${e.kind}${e.status ? ` (HTTP ${e.status})` : ""}`);
