import { ApiError, GoogleGenAI, ThinkingLevel } from "@google/genai";
import { createHash, timingSafeEqual } from "node:crypto";

// Google Gemini via the official Google Gen AI SDK. Server-only: GEMINI_API_KEY never reaches the browser.
//
// MODELS. Google retires models regularly (the 2.5 family is now restricted for new keys and answers 404), so:
//  - if GEMINI_MODEL is set we use exactly that model and nothing else;
//  - otherwise we try DEFAULT_MODELS in order, moving on ONLY when a model answers "not found" (404).
// Every candidate is a Gemini model ID with free-tier availability on Google's side. Choosing a different model ID
// cannot start billing: billing exists only if YOU enable it on your Google project. Diagnostics report the model used.
export const DEFAULT_MODELS = ["gemini-3.5-flash-lite", "gemini-3.1-flash-lite"];
const envModel = () => process.env.GEMINI_MODEL?.trim() || "";
export const modelCandidates = () => (envModel() ? [envModel()] : DEFAULT_MODELS);
export const geminiModel = () => modelCandidates()[0];
export const aiConfigured = () => !!process.env.GEMINI_API_KEY?.trim();

export type AiErrorKind =
  | "missing_key" | "invalid_key" | "permission_denied" | "model_not_found" | "quota" | "invalid_request"
  | "blocked" | "bad_output" | "timeout" | "network" | "provider";

export interface AiDiagnostics {
  httpStatus?: number;
  providerStatus?: string; // Google's enum-like status, e.g. NOT_FOUND, RESOURCE_EXHAUSTED
  providerReason?: string; // Google's error-detail reason, e.g. API_KEY_INVALID
  model?: string;          // which model was being called
  elapsedMs?: number;      // how long the call ran before failing
  detail?: string;         // redacted + truncated provider message. Developer-only; never sent to the public.
}

export class AiError extends Error {
  public status?: number; public providerStatus?: string; public providerReason?: string; public detail?: string; public model?: string; public elapsedMs?: number;
  constructor(public kind: AiErrorKind, d: AiDiagnostics = {}) {
    super(kind);
    this.status = d.httpStatus; this.providerStatus = d.providerStatus; this.providerReason = d.providerReason; this.detail = d.detail; this.model = d.model; this.elapsedMs = d.elapsedMs;
  }
  get diagnostics(): AiDiagnostics { return { httpStatus: this.status, providerStatus: this.providerStatus, providerReason: this.providerReason, model: this.model, elapsedMs: this.elapsedMs, detail: this.detail }; }
}

/** Plain-language message for the public UI. Never includes provider text. */
export function userMessage(kind: AiErrorKind, what: "analysis" | "assistant"): string {
  const tail = what === "analysis" ? "This analysis was generated by the built-in rule-based engine instead." : "This answer comes from the built-in offline assistant instead.";
  switch (kind) {
    case "missing_key": return `Gemini isn't configured on this server (GEMINI_API_KEY is missing). ${tail}`;
    case "invalid_key": return `The Gemini API key was rejected as invalid. Check GEMINI_API_KEY in your hosting settings. ${tail}`;
    case "permission_denied": return `Gemini denied permission for this key (restricted key, API not enabled, or unsupported region). ${tail}`;
    case "model_not_found": return `The configured Gemini model isn't available to this key (it may have been retired). ${tail}`;
    case "quota": return `The free Gemini quota is used up for now (rate or daily limit). Try again later. ${tail}`;
    case "invalid_request": return `Gemini rejected the request as invalid. ${tail}`;
    case "blocked": return `Gemini declined to answer this request. ${tail}`;
    case "bad_output": return `Gemini returned an answer we couldn't use. ${tail}`;
    case "timeout": return `Gemini took too long to respond. ${tail}`;
    case "network": return `The server couldn't reach the Gemini service. ${tail}`;
    default: return `The Gemini service is temporarily unavailable. ${tail}`;
  }
}

/** Remove anything that looks like a credential and cap length. Applied to every provider string we ever keep. */
export function redact(s: string, max = 300): string {
  let out = s
    .replace(/AIza[0-9A-Za-z_-]{20,}/g, "[redacted-key]")
    .replace(/(Bearer|Basic)\s+[A-Za-z0-9._~+/=-]{8,}/gi, "$1 [redacted]")
    .replace(/([?&](?:key|api_key|apikey|token|access_token)=)[^&\s"']+/gi, "$1[redacted]")
    .replace(/(x-goog-api-key["']?\s*[:=]\s*["']?)[^\s"',}]+/gi, "$1[redacted]");
  const secret = process.env.GEMINI_API_KEY?.trim();
  if (secret && secret.length >= 8) out = out.split(secret).join("[redacted-key]");
  out = out.replace(/\s+/g, " ").trim();
  return out.length > max ? out.slice(0, max) + "…" : out;
}

const ENUM = /^[A-Z][A-Z0-9_]{2,60}$/;

/** Pull Google's structured error out of an SDK error. Only whitelisted enum-like fields are kept verbatim. */
export function parseProviderError(err: unknown): { httpStatus?: number; providerStatus?: string; providerReason?: string; message: string } {
  const message = err instanceof Error ? err.message : typeof err === "string" ? err : "";
  let httpStatus = err instanceof ApiError ? err.status : typeof (err as { status?: unknown })?.status === "number" ? (err as { status: number }).status : undefined;
  let providerStatus: string | undefined, providerReason: string | undefined, text = message;
  const brace = message.indexOf("{");
  if (brace >= 0) {
    try {
      const j = JSON.parse(message.slice(brace)) as { error?: { code?: number; status?: string; message?: string; details?: { reason?: string }[] } };
      if (j.error) {
        if (typeof j.error.code === "number") httpStatus ??= j.error.code;
        if (j.error.status && ENUM.test(j.error.status)) providerStatus = j.error.status;
        const reason = j.error.details?.map((d) => d.reason).find((r): r is string => !!r && ENUM.test(r));
        if (reason) providerReason = reason;
        if (j.error.message) text = j.error.message;
      }
    } catch { /* message wasn't JSON */ }
  }
  return { httpStatus, providerStatus, providerReason, message: text };
}

export function classifyError(err: unknown): AiError {
  if (err instanceof AiError) return err;
  const p = parseProviderError(err);
  const d: AiDiagnostics = { httpStatus: p.httpStatus, providerStatus: p.providerStatus, providerReason: p.providerReason, detail: redact(p.message) };
  const name = err instanceof Error ? err.name : "";
  const s = p.httpStatus, text = p.message;
  const kind = (k: AiErrorKind) => new AiError(k, d);

  if (p.providerReason === "API_KEY_INVALID" || /API key not valid|API[_ ]KEY[_ ]INVALID|API key expired/i.test(text)) return kind("invalid_key");
  if (s === 401 || p.providerStatus === "UNAUTHENTICATED") return kind("invalid_key");
  if (s === 429 || p.providerStatus === "RESOURCE_EXHAUSTED") return kind("quota");
  if (s === 403 || p.providerStatus === "PERMISSION_DENIED") return kind("permission_denied");
  if (s === 404 || p.providerStatus === "NOT_FOUND") return kind("model_not_found");
  if (s === 400 || p.providerStatus === "INVALID_ARGUMENT" || p.providerStatus === "FAILED_PRECONDITION") return kind("invalid_request");
  if (name === "AbortError" || name === "TimeoutError" || s === 408 || s === 504 || /timed? ?out|aborted/i.test(text)) return kind("timeout");
  if (s === undefined && /fetch failed|ENOTFOUND|ECONNREFUSED|ECONNRESET|EAI_AGAIN|network|socket/i.test(`${text} ${name}`)) return kind("network");
  return kind("provider");
}

let lastGood: string | undefined; // per-instance memory so we don't re-probe retired models on every request

export interface GenerateResult { text: string; model: string; elapsedMs: number }
export interface GenerateOptions {
  system: string; prompt: string; json?: boolean; maxTokens?: number;
  /** TOTAL time budget for this whole call (all models, all attempts). Must be below the host's function limit. */
  totalMs?: number;
  /** "minimal" for short answers (fast, cheap on free quota); "low" for structured analysis. */
  thinking?: "minimal" | "low";
}
const MIN_ATTEMPT_MS = 4_000;

/**
 * Call Gemini once. Guarantees:
 *  - NO SDK retries (attempts:1 pinned explicitly; retries are opt-in in this SDK version, but pinning protects us if that default ever changes);
 *  - the whole call, across candidate models, stays inside `totalMs`;
 *  - next candidate model is tried only after "model not found" (404), and only if time remains;
 *  - throws AiError, never a raw provider error.
 */
export async function generateDetailed(opts: GenerateOptions): Promise<GenerateResult> {
  const key = process.env.GEMINI_API_KEY?.trim();
  if (!key) throw new AiError("missing_key");
  const started = Date.now();
  const deadline = started + (opts.totalMs ?? 40_000);
  const candidates = modelCandidates();
  const order = lastGood && candidates.includes(lastGood) ? [lastGood, ...candidates.filter((m) => m !== lastGood)] : candidates;
  let last: AiError | undefined;

  for (const model of order) {
    const remaining = deadline - Date.now();
    if (remaining < MIN_ATTEMPT_MS) { last ??= new AiError("timeout", { model, elapsedMs: Date.now() - started }); break; }
    // Per attempt: abort slightly before the deadline so we can still answer the visitor.
    const ai = new GoogleGenAI({ apiKey: key, httpOptions: { timeout: remaining, retryOptions: { attempts: 1 } } });
    const t0 = Date.now();
    let useThinking = true;
    for (let pass = 0; pass < 2; pass++) {
      try {
        const res = await ai.models.generateContent({
          model,
          contents: opts.prompt,
          config: {
            systemInstruction: opts.system,
            maxOutputTokens: opts.maxTokens ?? 6000,
            temperature: opts.json ? 0.7 : 0.6,
            ...(opts.json ? { responseMimeType: "application/json" } : {}),
            ...(useThinking ? { thinkingConfig: { thinkingLevel: opts.thinking === "low" ? ThinkingLevel.LOW : ThinkingLevel.MINIMAL } } : {}),
          },
        });
        if (res.promptFeedback?.blockReason) throw new AiError("blocked");
        const text = res.text;
        if (!text?.trim()) throw new AiError("bad_output");
        lastGood = model;
        return { text, model, elapsedMs: Date.now() - started };
      } catch (err) {
        last = classifyError(err);
        last.model ??= model; last.elapsedMs ??= Date.now() - t0;
        // A model that rejects the thinking setting: retry the SAME model once without it (bounded by the deadline).
        if (useThinking && last.kind === "invalid_request" && /think/i.test(last.detail ?? "") && deadline - Date.now() >= MIN_ATTEMPT_MS) { useThinking = false; continue; }
        break;
      }
    }
    if (!last || last.kind !== "model_not_found") throw last ?? new AiError("provider");
    if (lastGood === model) lastGood = undefined;
  }
  throw last ?? new AiError("provider");
}

export async function generate(opts: GenerateOptions): Promise<string> {
  return (await generateDetailed(opts)).text;
}

/** Developer-only: model IDs this key can use for generateContent (verifies GEMINI_MODEL against Google's live list). */
export async function listUsableModels(): Promise<string[]> {
  const key = process.env.GEMINI_API_KEY?.trim();
  if (!key) throw new AiError("missing_key");
  try {
    const ai = new GoogleGenAI({ apiKey: key, httpOptions: { timeout: 15_000 } });
    const out: string[] = [];
    const pager = await ai.models.list({ config: { pageSize: 100 } });
    for await (const m of pager) {
      if (m.name?.startsWith("models/gemini") && (!m.supportedActions || m.supportedActions.includes("generateContent"))) out.push(m.name.replace(/^models\//, ""));
      if (out.length >= 150) break;
    }
    return out.sort();
  } catch (err) { throw classifyError(err); }
}

export function extractJson(text: string): unknown {
  const start = text.indexOf("{"), end = text.lastIndexOf("}");
  if (start < 0 || end < start) throw new AiError("bad_output");
  try { return JSON.parse(text.slice(start, end + 1)); } catch { throw new AiError("bad_output"); }
}

/** Server log line: category, HTTP status, Google's status/reason enums and a redacted, truncated message. No keys, headers or payloads. */
export function logAiError(where: string, e: AiError) {
  const parts = [`kind=${e.kind}`, e.model ? `model=${e.model}` : "", e.elapsedMs !== undefined ? `elapsedMs=${e.elapsedMs}` : "", e.status ? `http=${e.status}` : "", e.providerStatus ? `status=${e.providerStatus}` : "", e.providerReason ? `reason=${e.providerReason}` : "", e.detail ? `detail="${redact(e.detail, 200)}"` : ""].filter(Boolean);
  console.error(`[${where}] Gemini call failed: ${parts.join(" ")}`);
}

/** Constant-time check of the developer token (header `Authorization: Bearer <AI_STATUS_TOKEN>`). Disabled when the env var is unset. */
export function isDeveloper(req: Request): boolean {
  const expected = process.env.AI_STATUS_TOKEN?.trim();
  if (!expected || expected.length < 16) return false;
  const m = /^Bearer\s+(.+)$/i.exec(req.headers.get("authorization") ?? "");
  if (!m) return false;
  const a = createHash("sha256").update(m[1].trim()).digest(), b = createHash("sha256").update(expected).digest();
  return timingSafeEqual(a, b);
}
