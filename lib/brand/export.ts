"use client";
// Client-side logo and brand-kit exports. Every file is built from the same vector scene, with text converted to outlines,
// so the SVG, PNG, JPEG and PDF show identical artwork and never depend on the viewer's fonts.
import { makeZip } from "../zip";
import { PdfDoc, Sheet } from "../pdf";
import { toSvg, type Vec } from "../vector/ir";
import { outlineScene } from "../vector/text";
import { preloadFonts } from "../vector/fontLoader";
import { blobBytes, svgToBlob, type RasterFormat } from "../raster";
import type { Direction } from "../types";
import { describe } from "./concepts";
import { colorsMd, graphicStyleMd, guidelinesMd, imageDirectionMd, personalityMd, slugOf, summaryMd, tokensCss, typographyMd } from "./kit";
import { clearSpace, MOCKUPS, mockup } from "./mockups";
import { ARCH, minSizes, renderLogo, type Fonts } from "./render";
import type { BrandProfile, ConceptSpec, Layout, Scheme } from "./types";

export async function loadBrandFonts(specs: ConceptSpec[]): Promise<Fonts> {
  const seen = new Set<string>(), pairs: { family: string; weight: number }[] = [];
  for (const s of specs) { const k = `${s.font.family}@${s.font.weight}`; if (!seen.has(k)) { seen.add(k); pairs.push(s.font); } }
  return { glyph: await preloadFonts(pairs) };
}

/** Outlines all text. Throws when a font could not be loaded, so a file with wrong lettering is never saved. */
export function outlined(vec: Vec, fonts: Fonts): Vec {
  const { vec: v, missing } = outlineScene(vec, fonts.glyph);
  if (missing.length) throw new Error(`The font ${missing.join(", ")} couldn't be loaded, so exporting would produce wrong lettering. Check your connection and try again.`);
  return v;
}

export const VARIANT_LABEL: Record<Scheme, string> = { full: "Full colour", reversed: "Reversed", black: "Black", white: "White" };
export const LAYOUT_LABEL: Record<Layout, string> = { primary: "Primary", horizontal: "Horizontal", stacked: "Stacked", symbol: "Symbol only", wordmark: "Wordmark only" };

export function logoName(spec: ConceptSpec, layout: Layout, scheme: Scheme, ext: string, suffix = ""): string {
  const l = layout === "primary" ? "primary" : layout;
  return `${slugOf(spec.name)}-logo-${slugOf(ARCH[spec.archetype].label)}-${l}-${scheme}${suffix}.${ext}`;
}

export function logoSvg(spec: ConceptSpec, layout: Layout, scheme: Scheme, fonts: Fonts) {
  const r = renderLogo(spec, layout, scheme, fonts);
  const vec = outlined(r.vec, fonts);
  return { name: logoName(spec, layout, scheme, "svg"), svg: toSvg(vec), vec, render: r };
}

export interface RasterOpts { format: RasterFormat; width: number; background: string | null; quality?: number }
export async function vecRaster(vec: Vec, o: RasterOpts) {
  const scale = o.width / vec.w;
  const r = await svgToBlob(toSvg(vec), vec.w, vec.h, { format: o.format, scale, background: o.background, quality: o.quality ?? 0.92 });
  return r;
}
export async function logoRaster(spec: ConceptSpec, layout: Layout, scheme: Scheme, fonts: Fonts, o: RasterOpts) {
  const { vec } = logoSvg(spec, layout, scheme, fonts);
  const r = await vecRaster(vec, o);
  return { ...r, name: logoName(spec, layout, scheme, o.format === "png" ? "png" : "jpg", `-${r.width}px`) };
}

const KEY_LAYOUTS: Layout[] = ["horizontal", "stacked", "symbol", "wordmark"];
const SCHEMES: Scheme[] = ["full", "reversed", "black", "white"];

/** A presentation sheet: lockups, rationale, colours, type, clear space, minimum sizes, mockups. Real selectable text. */
export async function logoPdf(spec: ConceptSpec, profile: BrandProfile, d: Direction, fonts: Fonts): Promise<{ name: string; bytes: Uint8Array }> {
  const a = describe(spec, profile), r = renderLogo(spec, "primary", "full", fonts), m = minSizes(r);
  const doc = new PdfDoc(`${spec.name} — logo concept`);
  const sh = new Sheet(doc, `${spec.name} · ${ARCH[spec.archetype].label} · generated by DesignPilot AI`);
  sh.para(ARCH[spec.archetype].label.toUpperCase(), { size: 9, font: "F2", color: "#7a6cff" });
  sh.heading(`${spec.name} — logo concept`, 22);
  sh.vec(outlined(renderLogo(spec, "primary", "full", fonts).vec, fonts), sh.width, 150, "#ffffff");
  sh.vec(outlined(renderLogo(spec, "primary", "reversed", fonts).vec, fonts), sh.width, 120);
  sh.h2("Concept");
  sh.table([["Idea", a.idea], ["Meaning", a.meaning], ["Shape language", a.shape], ["Typography", a.type], ["Colour", a.color], ["Personality", a.personality], ["Best use", a.bestUse], ["Weaknesses", a.weakness]], { keyW: 100 });
  sh.h2("Colour");
  sh.swatches([{ label: "Ink", hex: spec.palette.ink }, { label: "Accent", hex: spec.palette.accent }, { label: "Background", hex: spec.palette.bg }, { label: "Deep", hex: spec.palette.deep }], 48);
  sh.h2("Versions");
  for (const l of KEY_LAYOUTS) { sh.para(LAYOUT_LABEL[l], { size: 9, font: "F2" }); sh.vec(outlined(renderLogo(spec, l, "full", fonts).vec, fonts), 200, 70, "#ffffff"); }
  for (const s of SCHEMES.slice(1)) { sh.para(VARIANT_LABEL[s], { size: 9, font: "F2" }); sh.vec(outlined(renderLogo(spec, "primary", s, fonts).vec, fonts), 200, 70, s === "white" ? "#1b1b22" : s === "black" ? "#ffffff" : undefined); }
  sh.h2("Clear space and minimum size");
  sh.vec(outlined(clearSpace(spec, fonts), fonts), 260, 130);
  sh.bullets([`Clear space x = ${Math.round(r.pad)} units, a quarter of the symbol height (the zone shown above).`, `Minimum size (rule of thumb): ${m.digitalW}px wide on screen, about ${m.printMm}mm in print.`, "Below the minimum use the symbol-only version."]);
  sh.h2("Typography");
  sh.table([["Logo lettering", `${spec.font.family} ${spec.font.weight}${spec.caps ? ", capitals" : ""} (converted to outlines in logo files)`], ["Headings", d.fonts.heading], ["Body", d.fonts.body]], { keyW: 100 });
  sh.h2("Applications");
  for (const mk of MOCKUPS) { sh.para(mk.label, { size: 9, font: "F2" }); sh.vec(outlined(mockup(mk.id, spec, fonts), fonts), 340, 150); }
  sh.h2("Notes");
  sh.para("This is a design concept generated from your brief. DesignPilot has not checked it against existing logos or trademarks, so do that before commercial use.", { size: 9.5 });
  return { name: `${slugOf(spec.name)}-logo-${slugOf(ARCH[spec.archetype].label)}-presentation.pdf`, bytes: doc.build() };
}

export type KitPart = "logos" | "colors" | "typography" | "tokens" | "personality" | "guidelines" | "graphic" | "images" | "previews" | "pdf";
export const KIT_PARTS: { id: KitPart; label: string; hint: string }[] = [
  { id: "logos", label: "Logo files", hint: "SVG for every lockup and colour version, plus transparent PNGs" },
  { id: "colors", label: "Colours (HEX)", hint: "Logo and interface colours as Markdown and JSON" },
  { id: "typography", label: "Typography", hint: "Logo lettering, headings and body fonts" },
  { id: "tokens", label: "CSS tokens", hint: "brand-tokens.css with colours and font variables" },
  { id: "personality", label: "Brand personality", hint: "Your brand profile and the concept rationale" },
  { id: "guidelines", label: "Usage guidelines", hint: "Clear space, minimum size, do and don't" },
  { id: "graphic", label: "Icon & graphic style", hint: "From the selected direction" },
  { id: "images", label: "Image direction", hint: "From the selected direction" },
  { id: "previews", label: "Application previews", hint: "Business card, app icon, header, avatar as SVG and PNG" },
  { id: "pdf", label: "Guideline PDF", hint: "The logo presentation sheet" },
];

export async function brandKit(parts: KitPart[], spec: ConceptSpec, profile: BrandProfile, d: Direction, fonts: Fonts, onStep?: (s: string) => void): Promise<{ name: string; bytes: Uint8Array; files: string[] }> {
  const files: { name: string; content: string | Uint8Array }[] = [];
  const has = (p: KitPart) => parts.includes(p), slug = slugOf(spec.name);
  const add = (name: string, content: string | Uint8Array) => files.push({ name: `${slug}-brand-kit/${name}`, content });
  if (has("logos")) {
    onStep?.("Logo files");
    for (const l of KEY_LAYOUTS) for (const s of SCHEMES) {
      const x = logoSvg(spec, l, s, fonts); add(`logos/svg/${x.name}`, x.svg);
      const png = await vecRaster(x.vec, { format: "png", width: l === "symbol" ? 1024 : 2000, background: null });
      add(`logos/png/${logoName(spec, l, s, "png", `-${png.width}px`)}`, await blobBytes(png.blob));
    }
  }
  if (has("colors")) { add("colors/colors.md", colorsMd(spec, d)); add("colors/colors.json", JSON.stringify({ logo: spec.palette, interface: d.palette.colors }, null, 2)); }
  if (has("typography")) add("typography/typography.md", typographyMd(spec, d));
  if (has("tokens")) add("tokens/brand-tokens.css", tokensCss(spec, d));
  if (has("personality")) { add("brand/personality.md", personalityMd(profile)); add("brand/logo-concept.md", summaryMd(spec, profile)); }
  if (has("guidelines")) add("guidelines/logo-usage.md", guidelinesMd(spec, profile, fonts));
  if (has("graphic")) add("style/graphic-style.md", graphicStyleMd(spec, d));
  if (has("images")) add("style/image-direction.md", imageDirectionMd(spec, d));
  if (has("previews")) {
    onStep?.("Application previews");
    for (const mk of MOCKUPS) { const v = outlined(mockup(mk.id, spec, fonts), fonts); add(`previews/${slug}-${mk.id}.svg`, toSvg(v)); add(`previews/${slug}-${mk.id}.png`, await blobBytes((await vecRaster(v, { format: "png", width: 1600, background: null })).blob)); }
  }
  if (has("pdf")) { onStep?.("PDF"); const pdf = await logoPdf(spec, profile, d, fonts); add(`guidelines/${pdf.name}`, pdf.bytes); }
  add("README.txt", `${spec.name} brand kit\nGenerated by DesignPilot AI from your brief.\n\nContents: ${parts.join(", ")}.\nLogo files contain outlined lettering (no font needed). DesignPilot has not checked this logo against existing logos or trademarks.\n`);
  return { name: `${slug}-brand-kit.zip`, bytes: makeZip(files), files: files.map((f) => f.name) };
}
